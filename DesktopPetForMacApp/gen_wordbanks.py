def load_existing(name):
    path = BANK_DIR / f"{name}.json"
    if not path.exists():
        return set()
    return {item["word"] for item in json.load(open(path))}


def dump(name, pairs, drop):
    seen, out = set(), []
    for word, meaning in pairs:
        if word in seen or word in drop:
            continue
        seen.add(word)
        out.append({"word": word, "meaning": meaning})
    path = BANK_DIR / f"{name}.json"
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(out, fh, ensure_ascii=False, indent=2)
    print(f"{name}: {len(out)} words -> {path}")


def main():
    dump("cet4", CET4, set())
    cet4 = load_existing("cet4")
    dump("cet6", CET6, cet4)
    cet6 = load_existing("cet6")
    dump("ielts", IELTS, cet4 | cet6)
    dump("travel", TRAVEL, cet4 | load_existing("ielts"))


if __name__ == "__main__":
    main()
